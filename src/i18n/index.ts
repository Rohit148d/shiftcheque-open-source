export type Translator = (key: TranslationKey, values?: Record<string, string | number>) => string;

export function createTranslator(language: Language): Translator {
  const dictionary = language === 'fr-CA' ? fr : en;
  return (key, values) => {
    const template = (dictionary[key] ?? en[key] ?? key) as string;
    if (!values) return template;
    return template.replace(/\{(\w+)\}/g, (_, token: string) => String(values[token] ?? `{${token}}`));
  };
}

/** Locale-aware formatting helpers. */
export function formatMoney(value: bigint, language: Language, options: { cents?: boolean } = {}): string {
  const digits = options.cents === false ? 0 : 2;
  const units = Number(value) / 1_000_000;
  try {
    return new Intl.NumberFormat(language, {
      style: 'currency',
      currency: 'CAD',
      minimumFractionDigits: digits,
      maximumFractionDigits: digits,
    }).format(units);
  } catch {
    const fixed = units.toFixed(digits);
    return `${value < 0n ? '-' : ''}$${fixed}`;
  }
}

export function formatNumber(value: number, language: Language, digits = 0): string {
  try {
    return new Intl.NumberFormat(language, { minimumFractionDigits: digits, maximumFractionDigits: digits }).format(value);
  } catch {
    return value.toFixed(digits);
  }
}

export function formatDay(dateKey: string, language: Language, style: 'short' | 'long' | 'weekday' = 'short'): string {
  const [year, month, day] = dateKey.split('-').map(Number);
  const date = new Date(Date.UTC(year, month - 1, day));
  try {
    const options: Intl.DateTimeFormatOptions =
      style === 'long'
        ? { weekday: 'long', month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' }
        : style === 'weekday'
          ? { weekday: 'short', month: 'short', day: 'numeric', timeZone: 'UTC' }
          : { month: 'short', day: 'numeric', timeZone: 'UTC' };
    return new Intl.DateTimeFormat(language, options).format(date);
  } catch {
    return dateKey;
  }
}

export function formatClock(clock: string): string {
  const [hour, minute] = clock.split(':').map(Number);
  const suffix = hour >= 12 ? 'PM' : 'AM';
  const display = hour % 12 === 0 ? 12 : hour % 12;
  return `${display}:${String(minute).padStart(2, '0')} ${suffix}`;
}

